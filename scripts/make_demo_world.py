#!/usr/bin/env python3
"""World and GUI configuration for the interactive demo (scripts/demo.sh), with the Gazebo GUI.

usage: make_demo_world.py <hover|circle> <calm|paper|gusty>

Writes PX4-Autopilot/Tools/simulation/gz/worlds/ijc_demo.sdf (world name ijc_demo) and
logs/demo/gui.config (the default Gazebo GUI with an initial camera suited to the scenario).
The world is the experiment world of the chosen wind with the scene and markers of the videos, without
camera sensors:
  calm   ijc_calm (no wind)
  paper  ijc_wind (wind of S2/S3: WindEffects, mean 4 m/s, gusts 3-5 m/s, turbulence)
  gusty  ijc_calm + IjcGustSystem with the profile of the videos (fronts_sharp x 0.85); the wind is
         started by ijc_flight.py (--gust-topic) 8 s of simulated time before the scenario start
Markers (IjcVideoSystem): hover, green sphere at the reference and 5 s trail; circle, desired circle
as a ring at the flight altitude, sphere at the instantaneous desired position and one-lap trail;
blue arrow of the wind (paper: the mean wind, the gusts/turbulence of WindEffects are not shown).
"""
import math
import os
import sys

import make_video_worlds as mvw

from paths import ROOT  # noqa: E402  (repository root)
GUI_DEFAULT = '/usr/share/gz/gz-sim8/gui/gui.config'
WORLD = 'ijc_demo'
# initial GUI camera: offset from the point it looks at (ENU, m)
GUI_VIEW = {'hover': ((0.0, 0.0, 2.4), (2.2, -2.6, 0.9)),
            'circle': ((0.0, -2.0, 1.8), (2.0, -3.8, 5.2))}


def gui_config(kind):
    look, off = GUI_VIEW[kind]
    pos = [a + b for a, b in zip(look, off)]
    yaw = math.atan2(-off[1], -off[0])
    pitch = math.atan2(off[2], math.hypot(off[0], off[1]))   # positive: looking down
    s = open(GUI_DEFAULT).read()
    old = '<camera_pose>-6 0 6 0 0.5 0</camera_pose>'
    assert s.count(old) == 1
    s = s.replace(old, f'<camera_pose>{pos[0]:.2f} {pos[1]:.2f} {pos[2]:.2f} 0 {pitch:.3f} {yaw:.3f}</camera_pose>')
    s = s.replace('<width>1000</width>', '<width>1400</width>').replace('<height>845</height>', '<height>900</height>')
    return s


def main():
    kind, wind = sys.argv[1], sys.argv[2]
    assert kind in ('hover', 'circle') and wind in ('calm', 'paper', 'gusty')
    base_name = 'ijc_wind' if wind == 'paper' else 'ijc_calm'
    w = open(f'{mvw.GZ}/worlds/{base_name}.sdf').read()
    mvw.make_ground()
    w = w.replace(f'<world name="{base_name}">',
                  f'<world name="{WORLD}">\n    <!-- generated by scripts/make_demo_world.py {kind} {wind} -->', 1)
    anchor = '    <plugin filename="libIjcWrenchSystem.so" name="custom::IjcWrenchSystem">'
    assert w.count(anchor) == 1
    if wind == 'gusty':
        w = w.replace(anchor, mvw.gust_plugin('logs/demo/wind.csv') + anchor)
        w = w.replace('<gravity>0 0 -9.80665</gravity>',
                      '<gravity>0 0 -9.80665</gravity>\n    <wind><linear_velocity>0 0 0</linear_velocity></wind>')
    arrows = wind != 'calm'

    # scene: sky, shadows, textured ground (as in the videos)
    w = w.replace('<shadows>true</shadows>', '<shadows>true</shadows>\n      <sky></sky>')
    w = w.replace('<ambient>0.4 0.4 0.4 1</ambient>\n      <background>', '<ambient>0.3 0.3 0.3 1</ambient>\n      <background>')
    w = w.replace('<ambient>0.8 0.8 0.8 1</ambient>\n            <diffuse>0.8 0.8 0.8 1</diffuse>',
                  '<ambient>0.42 0.52 0.34 1</ambient>\n            <diffuse>0.42 0.52 0.34 1</diffuse>')
    sun = '<direction>0.001 0.625 -0.78</direction>'
    assert w.count(sun) == 1
    w = w.replace(sun, '<direction>-0.08 0.1 -0.99</direction>')

    # markers (IjcVideoSystem without camera); the desired-position sphere is timed from the
    # /ijc_gust_start message that ijc_flight.py sends 8 s before the scenario start (any wind)
    if kind == 'hover':
        plug = mvw.video_plugin('0 0 2.5', '1 -1 1', True, '0 0 3.6', 0.2)
        models = static_visual_ref()
        models += mvw.trail_models(50)
    else:
        extra = ('      <attach model="ijc_ring_air" offset="0 -2 2.5"/>\n'
                 '      <desired_model>ijc_des</desired_model>\n      <desired_topic>/ijc_gust_start</desired_topic>\n'
                 '      <desired_lead>8.0</desired_lead>\n      <desired_radius>2.0</desired_radius>\n'
                 '      <desired_period>20.0</desired_period>\n      <desired_ramp>5.0</desired_ramp>\n'
                 '      <reference_height>2.5</reference_height>\n')
        plug = mvw.video_plugin('0 -2 2.5', '1 -1 1', False, '0 -2 2.45', 0.23, trail=200, extra=extra)
        models = (mvw.ring_model('ijc_ring_air', center=(0.0, 0.0), z=0.0, width=0.03, height=0.03, alpha=0.35,
                                 pose='0 0 -20 0 0 0')
                  + mvw.static_visual('ijc_des', '<sphere><radius>0.08</radius></sphere>', (0.0, 0.85, 0.1), alpha=0.25,
                                      shadows=False)
                  + mvw.trail_models(200))
    if arrows:
        models += mvw.arrow_models()
    else:   # no wind entity: no arrow
        plug = plug.replace('<arrow_segment_prefix>ijc_arrow_seg_</arrow_segment_prefix>', '<arrow_segment_prefix></arrow_segment_prefix>')
    plug = plug.replace('<camera_model>ijc_cam</camera_model>', '<camera_model></camera_model>')
    w = w.replace(anchor, plug + anchor)
    ground = ''.join(f'    <include>\n      <name>ijc_ground_{i}_{j}</name>\n      <uri>model://ijc_ground</uri>\n'
                     f'      <pose>{32 * i} {32 * j} 0.002 0 0 0</pose>\n    </include>\n' for i in (-1, 0, 1) for j in (-1, 0, 1))
    light = '    <light name="sunUTC" type="directional">'
    assert w.count(light) == 1
    w = w.replace(light, ground + models + light)
    open(f'{mvw.GZ}/worlds/{WORLD}.sdf', 'w').write(w)

    os.makedirs(f'{ROOT}/logs/demo', exist_ok=True)
    with open(f'{ROOT}/logs/demo/gui.config', 'w') as f:
        f.write(gui_config(kind))
    print(f'demo world written: {WORLD} ({kind}, wind {wind})')


def static_visual_ref():
    return mvw.static_visual('ijc_ref', '<sphere><radius>0.12</radius></sphere>', (0.0, 0.85, 0.1), alpha=0.45, shadows=False)


if __name__ == '__main__':
    main()
